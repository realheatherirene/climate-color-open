/* ==========================================================================
   WORLD DOTS: the Story Map's base map, as a grid of dots
   ==========================================================================
   Each string is one row of the map, north to south; each character is one
   dot, west to east. "1" = land (draw a dot), "0" = water (leave empty).

   Grid: 3 degrees per dot, equirectangular. Row 0 is centered on latitude
   81°N and each row steps 3° south; column 0 is centered on longitude
   178.5°W and each column steps 3° east. story-map-logic.js uses the same
   numbers (DOT_DEG, LAT_TOP) to place story pins, so if you ever change
   the grid, change those constants too.

   Deliberately symbolic, not a precise coastline: it was rasterized from
   hand-traced continent outlines, so small islands and narrow seas are
   simplified. It's a plain data file inside the repo, so the map loads with
   no third-party map servers — no visitor's browser contacts anyone else,
   consistent with Climate Color's no-tracking promise. To tweak a
   coastline, just flip a 0 or 1.
   ========================================================================== */

